/**
 * 人や費目に付ける色。**アプリの中で1つの見本を使う。**
 *
 * 色を選ぶ場所が増えるたびに一覧を書くと、機能ごとに少しずつ違う色が混ざり、
 * 「スケジュールの青」と「家計簿の青」が別物になる。
 *
 * 赤と黄は入れていない。この2色は「超過」「残りわずか」を表すために
 * 取ってあり、意味のある色として使い回さない
 * （docs/07-budget-requirements.md 4.4）。
 *
 * ---
 * **並びは目で選んでいない。** 隣り合う色が見分けられるかを計算で確かめ、
 * その中でいちばん良い並びを選んである。検証した結果（明・暗の両方）:
 *
 *   隣り合う色      通常の見え方 ΔE 16.3（基準15以上）/ 色覚の違い ΔE 9.2（基準8以上）
 *   先頭4色の総当たり 通常の見え方 ΔE 16.3 / 色覚の違い ΔE 10.3
 *
 * **確かに見分けられると言えるのは先頭4色まで。** 5色目からは、
 * どう並べても総当たりでは基準を割る（色の数を増やして解決できる問題ではない）。
 * そのため色だけに頼らず、**人の名前を必ず横に置く**。
 * カレンダーの予定も、色の帯とタイトルの文字が並ぶ形にしてある。
 *
 * 色を足したり並べ替えたりするときは、目で決めずに確かめること。
 */

/**
 * 人の色。`pick_member_color()`（DB側）もこの並びで配る。
 * 先頭から配るので、4人までの家族は確実に見分けられる色になる。
 */
export const HUES = [
  "#2563eb",
  "#0891b2",
  "#65a30d",
  "#db2777",
  "#4f46e5",
  "#ea580c",
  "#c026d3",
  "#16a34a",
  "#0284c7",
  "#7c3aed",
] as const;

/**
 * 落ち着いた色。めったに出てこない費目に使う。
 * 彩度が低く、色としての見分けはつかない。**名前と並べて初めて意味を持つ。**
 */
export const MUTED = [
  "#0f766e",
  "#475569",
  "#57534e",
  "#78716c",
  "#71717a",
] as const;

/** 費目の色。数が多いので、落ち着いた色まで含める */
export const PALETTE = [...HUES, ...MUTED];

/** 色として受け取ってよい形か。DB 側にも同じ制限がある */
export function isColor(value: string): boolean {
  return /^#[0-9a-fA-F]{6}$/.test(value);
}
